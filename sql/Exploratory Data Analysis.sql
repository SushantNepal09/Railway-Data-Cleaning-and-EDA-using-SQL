-- c) Revenue Ticket Types

# 1) Total number of revenue generated by each ticket type

select `Ticket Type`, 
COUNT(`Ticket Type`) as Number_of_Tickets,
SUM(`Price(GBP)`) as `Total Revenue`,
ROUND(AVG(`Price(GBP)`),2) as `Average Price`
FROM railway_cleaned
GROUP BY `Ticket Type`
ORDER BY `Total Revenue` DESC
;

-- d) Standard vs first class

WITH try_total AS
(SELECT `Ticket Class`, 
COUNT(`Ticket Class`) as total_tickets, 
ROUND(AVG(`Price(GBP)`),2) as avg_price,
MIN(`Price(GBP)`) as min_price,
MAX(`Price(GBP)`) as max_price,
SUM(`Price(GBP)`) as revenue
FROM railway_cleaned
GROUP BY `Ticket Class`)
SELECT *,
SUM(`revenue`) over(ORDER BY `Ticket Class`) as Rolling_total
FROM try_total;


-- e) Find the busiest routes

# 1) Finding the top 10 most frequently travelled routes

WITH routes_details as
(SELECT 
CONCAT(`Departure Station` ,' ','->' ,' ',`Arrival Destination`) as Routes
FROM railway_cleaned
)
SELECT *, 
COUNT(routes) as Travelled_frequency
FROM routes_details
GROUP BY routes
ORDER BY Travelled_frequency DESC
LIMIT 10
;

-- f) Finding the most expensive routes

# 1) Find 10 routes with the highest average prices (Routes with atleast 10 journey)

WITH routes_details as
(SELECT `Price(GBP)`,
CONCAT(`Departure Station` ,' ','->' ,' ',`Arrival Destination`) as Routes
FROM railway_cleaned
)
SELECT 
Routes,
COUNT(routes) as Travelled_frequency,
ROUND(AVG(`Price(GBP)`),2) as Average_Price
FROM routes_details
GROUP BY Routes
HAVING Travelled_frequency >= 10
ORDER BY Average_Price DESC
LIMIT 10
;

-- g) Railway Reliability

SELECT `Journey Status`,
COUNT(`Journey Status`) as Number_of_Journeys,
CASE
	WHEN `Journey Status` = 'Delayed' THEN ROUND(COUNT(`Journey Status`) * 100/sum(count(*)) over(),2)
	WHEN `Journey Status` = 'On-Time' THEN ROUND(COUNT(`Journey Status`) * 100/sum(count(*)) over(),2)
    WHEN `Journey Status` = 'Cancelled' THEN ROUND(COUNT(`Journey Status`) * 100/sum(count(*)) over(),2)
END AS Percentage
FROM railway_cleaned
GROUP BY `Journey Status`
ORDER BY Percentage DESC
;

-- h) What causes delays?

SELECT `Reason for Delay`,
COUNT(`Reason for Delay`) as `Number of Delays`,
ROUND((COUNT(`Reason for Delay`)*100/sum(count(*))over()),2) as Percentage_delay
FROM railway_cleaned
WHERE `Journey Status` = 'Delayed'
GROUP BY `Reason for Delay`
ORDER BY Percentage_delay DESC
;

-- i) Delay vs Ticket Class



SELECT `Ticket Class`,
