-- j) Delays vs Refund
# 1) Find Refund Rate for each journey status

SELECT * 
FROM railway_cleaned;

SELECT `Journey Status`,
COUNT(`Journey Status`) as `Total Journeys`,
SUM(`Refund Request`) as `Refund Request`,
ROUND(SUM(`Refund Request`) * (100) / COUNT(`Journey Status`),2) as `Refund Rate(%)`
FROM railway_cleaned
WHERE `Journey Status` != 'On-Time'
GROUP BY `Journey Status`
ORDER BY `Refund Rate(%)` DESC
;


-- k) Does buying earlier mean cheaper tickets?

SELECT * FROM
railway_cleaned;

with earlier_cheaper as
(SELECT `Date of Purchase`,
`Date of Journey`
,DATEDIFF(`Date of Journey` , `Date of Purchase`)
,`Price(GBP)`,
CASE 
	WHEN (DATEDIFF(`Date of Journey` , `Date of Purchase`)) <= 3 THEN '0-3 days'
    WHEN (DATEDIFF(`Date of Journey` , `Date of Purchase`)) BETWEEN 4 AND 7 THEN '4-7 days'
	WHEN (DATEDIFF(`Date of Journey` , `Date of Purchase`)) BETWEEN 8 AND 14 THEN '8-14 days'
    WHEN (DATEDIFF(`Date of Journey` , `Date of Purchase`)) BETWEEN 15 AND 30 THEN '15-30 days'
    WHEN (DATEDIFF(`Date of Journey` , `Date of Purchase`)) > 30 THEN '30+ Days'
END as `Booking Window`
FROM railway_cleaned
)
SELECT `Booking Window`,
COUNT(`Booking Window`) as `Number of Tickets`,
ROUND(AVG(`Price(GBP)`),2) as `Average Price`
FROM earlier_cheaper
GROUP BY `Booking Window`
ORDER BY `Average Price`
;



-- l) Final challange

# 1) Which route generates the most revenue?

SELECT 
CONCAT(`Departure Station` ,' ','->' ,' ',`Arrival Destination`) as Routes,
SUM(`Price(GBP)`) as `total_revenue(GBP)`
FROM railway_cleaned
GROUP BY Routes
