-- A) Basic dataset exploration

# 1) Total Number of Journey

SELECT count(*) as total_journeys
FROM railway_cleaned;

# 2) Number of Unique Departure Station
SELECT COUNT(DISTINCT `Departure Station`) as unique_departure_station
FROM railway_cleaned
;

# 3) Number of unique arrival destinations
SELECT COUNT(DISTINCT `Arrival Destination`)
FROM railway_cleaned;

# 4) Maximum,Minimum and Average Ticket Price
SELECT MAX(`Price(GBP)`) as max_price,
MIN(`Price(GBP)`) as min_price,
Round(AVG(`Price(GBP)`),2) as avg_price
From railway_cleaned
WHERE `Price(GBP)` IS NOT NULL
;
# 5) Number of Unique Ticket Types

SELECT COUNT(DISTINCT `Ticket Type`) as unique_types
FROM railway_cleaned
;

-- B)What people are buying?

# 1) Total Number of journey for Ticket class

SELECT `Ticket Class`,
COUNT(`Ticket Class`) as number_of_tickets
FROM railway_cleaned
GROUP BY `Ticket Class`
ORDER BY number_of_tickets DESC;

# 2) Total Number of journey by Ticket Type

SELECT `Ticket Type`,
COUNT(`Ticket Type`) as number_of_people
FROM railway_cleaned
