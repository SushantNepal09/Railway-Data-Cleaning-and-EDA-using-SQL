# 2) Which ticket type has the highest average price but isn't necessarily the highest-selling?

SELECT `Ticket Type`,
ROUND(AVG(`Price(GBP)`),2) as avg_price,
COUNT(`Ticket Type`) as quantity_sold
FROM railway_cleaned
GROUP BY `Ticket Type`
ORDER BY avg_price DESC;

# 3) Which delay reason has the highest refund-request rate?

SELECT `Reason for Delay`
,SUM(`Refund Request`) as Refund_Request
,SUM(`Refund Request`) *100 / COUNT(`Refund Request`) as `Refund_Rate(%)`
FROM railway_cleaned
WHERE `Reason for Delay` !=""
AND `Journey Status` != 'On-Time'
GROUP BY `Reason for Delay`
ORDER BY `Refund_Rate(%)` DESC
;




# 4) Which month has the most journeys and which month generates the most revenue?

SELECT
MONTH(`Date of Journey`) as month_number,
MONTHNAME(`Date of Journey`) AS month_name, 
COUNT(`Date of Journey`) as total_journey,
SUM(`Price(GBP)`) as revenue_month
FROM railway_cleaned
GROUP BY month_name,month_number
ORDER BY total_journey DESC;

SELECT 
substring_index(substring_index(`Date of Journey`,'-',2),'-',-1) as month_index,
SUM(`Price(GBP)`) as revenue_month
FROM railway_cleaned
GROUP BY month_index
ORDER by revenue_month DESC;








